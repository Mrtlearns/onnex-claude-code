-- Sprint 6: RAG evaluation results table
CREATE TABLE IF NOT EXISTS poc_ragv1.eval_results (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  retrieval_event_id  bigint NOT NULL REFERENCES poc_ragv1.chat_retrieval_events(id) ON DELETE CASCADE,
  faithfulness_score  numeric(4,3),
  relevance_score     numeric(4,3),
  groundedness_score  numeric(4,3),
  faithfulness_reason text,
  relevance_reason    text,
  groundedness_reason text,
  eval_model_used     text,
  eval_cost_usd       numeric(12,8) NOT NULL DEFAULT 0,
  created_at          timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_eval_results_retrieval_event
  ON poc_ragv1.eval_results(retrieval_event_id);

CREATE INDEX IF NOT EXISTS idx_eval_results_created_at
  ON poc_ragv1.eval_results(created_at DESC);

ALTER TABLE poc_ragv1.eval_results ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view own eval results"
  ON poc_ragv1.eval_results FOR SELECT
  USING (
    poc_ragv1.get_chat_session_project_owner(
      (SELECT chat_session_id FROM poc_ragv1.chat_retrieval_events
       WHERE id = eval_results.retrieval_event_id)
    ) = auth.uid()
  );

CREATE POLICY "Service role can insert eval results"
  ON poc_ragv1.eval_results FOR INSERT WITH CHECK (true);

GRANT ALL ON ALL TABLES IN SCHEMA poc_ragv1 TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA poc_ragv1 TO anon, authenticated, service_role;
