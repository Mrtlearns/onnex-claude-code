-- For chunks, we need to go through documents -> projects
CREATE OR REPLACE FUNCTION public.get_document_project_owner(p_document_id bigint)
RETURNS uuid
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT p.owner_id FROM public.projects p JOIN public.documents d ON d.project_id = p.id WHERE d.id = p_document_id;
$$;

