CREATE OR REPLACE FUNCTION poc_ragv1.handle_new_user()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = poc_ragv1 AS $$
BEGIN
  INSERT INTO poc_ragv1.profiles (id, display_name)
  VALUES (NEW.id, COALESCE(NEW.raw_user_meta_data->>'display_name', NEW.email));
  RETURN NEW;
END;
$$;

