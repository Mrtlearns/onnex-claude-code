-- Organizations table
CREATE TABLE IF NOT EXISTS poc_ragv1.organizations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  slug text UNIQUE NOT NULL,
  owner_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE poc_ragv1.organizations ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view orgs they own or belong to"
  ON poc_ragv1.organizations FOR SELECT
  USING (
    auth.uid() = owner_id OR
    EXISTS (SELECT 1 FROM poc_ragv1.org_members WHERE org_id = organizations.id AND user_id = auth.uid())
  );

CREATE POLICY "Users can create orgs"
  ON poc_ragv1.organizations FOR INSERT
  WITH CHECK (auth.uid() = owner_id);

CREATE POLICY "Owners can update orgs"
  ON poc_ragv1.organizations FOR UPDATE
  USING (auth.uid() = owner_id);

-- Org members table
CREATE TABLE IF NOT EXISTS poc_ragv1.org_members (
  org_id bigint NOT NULL REFERENCES poc_ragv1.organizations(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  role text NOT NULL DEFAULT 'member',
  joined_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, user_id)
);

ALTER TABLE poc_ragv1.org_members ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Members can view org membership"
  ON poc_ragv1.org_members FOR SELECT
  USING (
    user_id = auth.uid() OR
    EXISTS (SELECT 1 FROM poc_ragv1.organizations WHERE id = org_members.org_id AND owner_id = auth.uid())
  );

CREATE POLICY "Owners can manage members"
  ON poc_ragv1.org_members FOR ALL
  USING (
    EXISTS (SELECT 1 FROM poc_ragv1.organizations WHERE id = org_members.org_id AND owner_id = auth.uid())
  );

-- Add org_id to projects (nullable — backward compatible)
ALTER TABLE poc_ragv1.projects
  ADD COLUMN IF NOT EXISTS org_id bigint REFERENCES poc_ragv1.organizations(id) ON DELETE SET NULL;

-- Service role grants
GRANT ALL ON ALL TABLES IN SCHEMA poc_ragv1 TO service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA poc_ragv1 TO service_role;
